def build_original_huffman_lookup(weights_table):
    """Строит дерево Хаффмана строго по оригинальным 93 элементам таблицы весов."""
    heap = []
    counter = 0
    for key_hex, weight in weights_table.items():
        try:
            char_id = int(key_hex, 16)
            node = {'id': char_id, 'left': None, 'right': None}
            heapq.heappush(heap, (weight, counter, node))
            counter += 1
        except ValueError:
            continue

    if not heap:
        return {}
    while len(heap) > 1:
        w1, _, n1 = heapq.heappop(heap)
        w2, _, n2 = heapq.heappop(heap)
        heapq.heappush(heap, (w1 + w2, counter, {'id': None, 'left': n1, 'right': n2}))
        counter += 1

    _, _, root_node = heapq.heappop(heap)
    huffman_lookup = {}
    
    def walk_tree(node, current_code):
        if node['id'] is not None:
            huffman_lookup[current_code] = node['id']
            return
        if node['left']:
            walk_tree(node['left'], current_code + "0")
        if node['right']:
            walk_tree(node['right'], current_code + "1")

    walk_tree(root_node, "")
    return huffman_lookup


def build_canonical_huffman_lookup(weights_table):
    """
      # noqa
    Строит каноническое дерево Хаффмана для всех 256 возможных байтовых значений.
    Возвращает словарь: { 'бинарный_код_строкой': целочисленный_байт }

    Именно такую структуру процессоры ARM/SH-4 в Dayton v34 разбирают 
    на аппаратном уровне за один такт через быструю индексацию массивов, 
    не выполняя долгий рекурсивный обход узлов дерева по указателям памяти.
    """
    # Шаг 1: Инициализируем полный массив весов для всех 256 байт
    # Всем отсутствующим в заголовке байтам даем минимальный вес 1, чтобы дерево было полным # noqa
    full_weights = {b: 1 for b in range(256)}
    for key_hex, weight in weights_table.items():
        try:
            byte_id = int(key_hex, 16)
            if 0 <= byte_id <= 255:
                full_weights[byte_id] = weight
        except ValueError:
            continue

    # Шаг 2: Строим классическое дерево Хаффмана для вычисления только ДЛИН кодов
    heap = []
    counter = 0
    for byte_id, weight in full_weights.items():
        # Узел: (вес, счетчик, элемент)
        heapq.heappush(heap, (weight, counter, {'id': byte_id, 'left': None, 'right': None}))   # noqa
        counter += 1

    while len(heap) > 1:
        w1, _, n1 = heapq.heappop(heap)
        w2, _, n2 = heapq.heappop(heap)
        parent = {'id': None, 'left': n1, 'right': n2}
        heapq.heappush(heap, (w1 + w2, counter, parent))
        counter += 1

    _, _, root_node = heapq.heappop(heap)
    
    # Рекурсивно собираем длины кодов (code lengths) для каждого байта
    code_lengths = {}

    def collect_lengths(node, current_depth):
        if node['id'] is not None:
            code_lengths[node['id']] = current_depth
            return
        if node['left']:
            collect_lengths(node['left'], current_depth + 1)
        if node['right']:
            collect_lengths(node['right'], current_depth + 1)

    collect_lengths(root_node, 0)

    # Шаг 3: Превращаем обычные длины в Канонические длины кодов
    # Сортируем элементы: сначала по возрастанию длины кода, затем по значению байта (алфавитно)  # noqa
    sorted_elements = sorted(code_lengths.items(), key=lambda x: (x[1], x[0]))

    canonical_lookup = {}
    current_code_int = 0
    last_length = 0

    # Шаг 4: Последовательная генерация канонических кодов по правилам ГИС PSF
    for byte_id, length in sorted_elements:
        if length == 0:
            continue
            
        # Если длина кода увеличилась, сдвигаем текущее числовое значение влево
        if last_length > 0:
            current_code_int <<= (length - last_length)
            
        # Форматируем целочисленное значение в бинарную строку нужной длины
        bit_code = f"{current_code_int:0{length}b}"
        
        # Записываем в lookup-мапу для декодера: биты -> байт
        canonical_lookup[bit_code] = byte_id
        
        # Переходим к следующему каноническому коду (просто прибавляем 1)
        current_code_int += 1
        last_length = length

    return canonical_lookup


def print_lookup(lookup: dict):
    # Сортировка по длине ключа
    sorted_items = sorted(lookup.keys(), key=lambda item: (len(item), int(item, 2)))
    i_len = 0
    # Печать результата
    for key in sorted_items:
        value = lookup[key]
        if len(key) != i_len:
            i_len = len(key)
            print(f"\n[Длина: {i_len} бита]")
        if 0x20 <= value < 0x8A:
            pr_str = f"'{key}': 0x{value:02x}={value:02} ('{chr(value)}')"
        else:
            pr_str = f"'{key}': 0x{value:02x}={value:02}"
        print(pr_str)


