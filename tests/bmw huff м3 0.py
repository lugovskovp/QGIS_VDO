def auto_extract_huffman_weights(header_hex_string):
    # Очищаем строку от префиксов '0x' и пробелов, переводим в байты
    clean_hex = header_hex_string.replace("0x", "").replace(" ", "").replace("\n", "")
    file_bytes = binascii.unhexlify(clean_hex)
    
    print("=== АВТОМАТИЧЕСКИЙ РАЗБОР ЗАГЛОВКА ===")
    if len(file_bytes) < 0x2C:
        print("Ошибка: Слишком короткий поток байт.")
        return None
        
    # Извлекаем метаданные из смещения 0x28
    table_offset = int.from_bytes(file_bytes[0x28:0x2A], byteorder='big')
    pair_count = int.from_bytes(file_bytes[0x2A:0x2C], byteorder='big')
    
    print(f"Смещение 0x28 содержит указатели: {file_bytes[0x28:0x2C].hex().upper()}")
    print(f"  -> Вычисленный адрес таблицы весов:  0x{table_offset:04X} ({table_offset} байт)")
    print(f"  -> Количество пар (ключ-вес):        0x{pair_count:04X} ({pair_count} элементов)")
    
    print("\n=== ДИНАМИЧЕСКИЙ СБОР ТАБЛИЦЫ ВЕСОВ ===")
    weights_table = {}
    ptr = table_offset
    
    # Шагаем по таблице структурами по 4 байта (2 байта ключ + 2 байта вес)
    for i in range(pair_count):
        if ptr + 4 > len(file_bytes):
            print(f"Предупреждение: Достигнута граница дампа на элементе {i+1}.")
            break
            
        key_id = int.from_bytes(file_bytes[ptr:ptr+2], byteorder='big')
        weight = int.from_bytes(file_bytes[ptr+2:ptr+4], byteorder='big')
        
        # Сохраняем в итоговый словарь
        weights_table[f"0x{key_id:04X}"] = weight
        ptr += 4
        
    print(f"Успешно обработано элементов: {len(weights_table)}")
    return weights_table

